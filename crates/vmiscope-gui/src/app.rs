/// How often the Network tab re-snapshots the connection table.
const NET_REFRESH_SECS: f64 = 1.5;
/// How long a closed connection lingers (fading) before it disappears.
const NET_FADE_SECS: f64 = 6.0;

/// The top-level tools.
#[derive(PartialEq, Eq, Clone, Copy)]
enum Tab {
    Explorer,
    Network,
    Persistence,
    Providers,
    Events,
}

/// A connection tracked across snapshots so it can fade out after it closes.
struct TrackedConn {
    conn: Connection,
    last_seen: f64,
    /// Present in the most recent snapshot?
    alive: bool,
}

/// What an in-flight request id was asking for — used to clear the correct
/// loading state when a reply (or error) arrives.
enum PendingKind {
    Namespaces(String),
    Classes,
    Query,
    Network,
    Events,
    Providers,
    Schema,
    Mof,
    Instances,
    Invoke,
    Search,
    Connect,
}

/// A dangerous-looking method name gets an extra warning in the confirm modal.
fn is_dangerous_method(method: &str) -> bool {
    let m = method.to_lowercase();
    [
        "create",
        "delete",
        "terminate",
        "reboot",
        "shutdown",
        "format",
        "change",
        "rename",
        "uninstall",
        "setpowerstate",
        "stopservice",
        "kill",
        "write",
        "set",
    ]
    .iter()
    .any(|k| m.contains(k))
}

/// Open a native "Save as" dialog and write `contents` to the chosen path.
fn save_file(default_name: &str, contents: &str) {
    if let Some(path) = rfd::FileDialog::new()
        .set_file_name(default_name)
        .save_file()
    {
        let _ = std::fs::write(path, contents);
    }
}

/// Colour for a subscription risk level.
fn risk_color(risk: Risk) -> Color32 {
    match risk {
        Risk::High => Color32::from_rgb(240, 100, 100),
        Risk::Medium => Color32::from_rgb(225, 185, 90),
        Risk::Low => Color32::from_rgb(150, 165, 150),
    }
}

