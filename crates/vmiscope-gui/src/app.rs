    // ------------------------------------------------------------------
    // request helpers
    // ------------------------------------------------------------------

    fn alloc_id(&mut self) -> u64 {
        self.next_id += 1;
        self.next_id
    }

    /// Record an error: keep it as the latest, and accumulate into a bounded log
    /// (so a burst of errors doesn't lose all but the last).
    fn push_error(&mut self, msg: String) {
        self.error_log.insert(0, msg.clone());
        self.error_log.truncate(50);
        self.error = Some(msg);
    }

    fn request_namespaces(&mut self, namespace: String) {
        if self.ns_loading.contains(&namespace) || self.ns_children.contains_key(&namespace) {
            return;
        }
        let id = self.alloc_id();
        self.ns_loading.insert(namespace.clone());
        self.pending
            .insert(id, PendingKind::Namespaces(namespace.clone()));
        self.worker
            .send(Request::ListChildNamespaces { id, namespace });
    }

    fn request_classes(&mut self, namespace: String) {
        self.classes_ns = namespace.clone();
        // Serve from cache instantly when we've already enumerated this namespace.
        if let Some(cached) = self.class_cache.get(&namespace) {
            self.classes = cached.clone();
            self.classes_loading = false;
            return;
        }
        let id = self.alloc_id();
        self.classes_loading = true;
        self.classes.clear();
        self.pending.insert(id, PendingKind::Classes);
        self.worker.send(Request::ListClasses { id, namespace });
    }

    fn request_network(&mut self, now: f64) {
        let id = self.alloc_id();
        self.net_inflight = true;
        self.net_last_refresh = now;
        self.pending.insert(id, PendingKind::Network);
        self.worker.send(Request::NetworkSnapshot { id });
    }

    fn request_events(&mut self) {
        let id = self.alloc_id();
        self.events_loading = true;
        self.pending.insert(id, PendingKind::Events);
        self.worker.send(Request::ListEventSubscriptions { id });
    }

    fn request_providers(&mut self) {
        let id = self.alloc_id();
        self.providers_loading = true;
        self.pending.insert(id, PendingKind::Providers);
        self.worker.send(Request::ListProviders { id });
    }

    fn request_schema(&mut self, class: String) {
        if class.is_empty() {
            return;
        }
        // Already have (or are fetching) this class's schema.
        if self.schema_class == class && (self.schema.is_some() || self.schema_loading) {
            return;
        }
        let id = self.alloc_id();
        self.schema_class = class.clone();
        self.schema = None;
        self.schema_loading = true;
        self.pending.insert(id, PendingKind::Schema);
        self.worker.send(Request::ClassSchema {
            id,
            namespace: self.active_ns.clone(),
            class,
        });
    }

    fn request_search_index(&mut self, include_methods: bool) {
        let id = self.alloc_id();
        self.search_loading = true;
        self.pending.insert(id, PendingKind::Search);
        self.worker.send(Request::BuildSearchIndex {
            id,
            namespace: self.active_ns.clone(),
            include_methods,
        });
    }

    fn apply_host(&mut self, host: Option<String>, cred: Option<Credential>) {
        let id = self.alloc_id();
        self.conn_status = ConnStatus::Connecting;
        self.pending.insert(id, PendingKind::Connect);
        self.worker.send(Request::SetHost { id, host, cred });
    }

    /// Wipe host-scoped state and re-seed the tree/query for a new target.
    fn reset_and_reseed(&mut self) {
        self.ns_children.clear();
        self.ns_expanded.clear();
        self.ns_loading.clear();
        self.class_cache.clear();
        self.classes.clear();
        self.classes_ns.clear();
        self.selected_class = None;
        self.result = None;
        self.selected_row = None;
        self.schema = None;
        self.schema_class.clear();
        self.search_index = None;
        self.net_conns.clear();
        self.providers = None;
        self.events_report = None;
        self.act_instances = None;
        self.active_ns = DEFAULT_NAMESPACE.to_string();
        self.ns_expanded.insert(ROOT_NAMESPACE.to_string());
        self.request_namespaces(ROOT_NAMESPACE.to_string());
        self.request_classes(DEFAULT_NAMESPACE.to_string());
        self.run_query();
    }

    fn request_instances(&mut self, class: String) {
        let id = self.alloc_id();
        self.act_instances_loading = true;
        self.pending.insert(id, PendingKind::Instances);
        self.worker.send(Request::ListInstances {
            id,
            namespace: self.active_ns.clone(),
            class,
        });
    }

    fn request_invoke(
        &mut self,
        class: String,
        object_path: String,
        method: String,
        is_static: bool,
        args: Vec<MethodArg>,
    ) {
        let id = self.alloc_id();
        self.act_invoking = true;
        self.act_outcome = None;
        self.pending.insert(id, PendingKind::Invoke);
        self.worker.send(Request::InvokeMethod {
            id,
            namespace: self.active_ns.clone(),
            class,
            object_path,
            method,
            is_static,
            args,
        });
    }

    fn request_mof(&mut self, object_path: String, title: String) {
        let id = self.alloc_id();
        self.mof_open = true;
        self.mof_loading = true;
        self.mof_title = title;
        self.mof_object_path = object_path.clone();
        self.mof_text = None;
        self.pending.insert(id, PendingKind::Mof);
        self.worker.send(Request::ClassMof {
            id,
            namespace: self.active_ns.clone(),
            object_path,
        });
    }

    fn run_query(&mut self) {
        let wql = self.query_text.trim().to_string();
        if wql.is_empty() {
            return;
        }
        self.config.push_history(&wql);
        let id = self.alloc_id();
        self.latest_query_id = id;
        self.query_loading = true;
        self.error = None;
        self.pending.insert(id, PendingKind::Query);
        self.worker.send(Request::Query {
            id,
            namespace: self.active_ns.clone(),
            wql,
        });
    }

    // ------------------------------------------------------------------
    // selection actions
    // ------------------------------------------------------------------

    fn select_namespace(&mut self, namespace: String) {
        if self.active_ns == namespace {
            return;
        }
        self.active_ns = namespace.clone();
        self.selected_class = None;
        self.schema = None;
        self.schema_class.clear();
        self.request_classes(namespace);
    }

    fn toggle_namespace(&mut self, path: &str) {
        if self.ns_expanded.contains(path) {
            self.ns_expanded.remove(path);
        } else {
            self.ns_expanded.insert(path.to_string());
            self.request_namespaces(path.to_string());
        }
    }

    fn select_class(&mut self, class: String) {
        self.query_text = format!("SELECT * FROM {class}");
        self.selected_class = Some(class.clone());
        self.run_query();
        if self.central_view == CentralView::Schema {
            self.request_schema(class);
        }
    }

    // ------------------------------------------------------------------
    // response handling
    // ------------------------------------------------------------------

    fn handle_responses(&mut self, now: f64) {
        for resp in self.worker.poll() {
            match resp {
                Response::ChildNamespaces {
                    id,
                    namespace,
                    children,
                } => {
                    self.pending.remove(&id);
                    self.ns_loading.remove(&namespace);
                    self.ns_children.insert(namespace, children);
                }
                Response::Classes {
                    id,
                    namespace,
                    classes,
                } => {
                    self.pending.remove(&id);
                    // Only apply if it still matches the namespace we care about.
                    if namespace == self.classes_ns {
                        self.classes = classes.clone();
                        self.classes_loading = false;
                    }
                    self.class_cache.insert(namespace, classes);
                }
                Response::QueryResult {
                    id, wql, result, ..
                } => {
                    self.pending.remove(&id);
                    // Ignore stale results from superseded queries.
                    if id == self.latest_query_id {
                        self.result = Some(result);
                        self.result_wql = wql;
                        self.selected_row = None;
                        self.result_sort = None;
                        self.query_loading = false;
                        self.error = None;
                    }
                }
                Response::Network { id, snapshot } => {
                    self.pending.remove(&id);
                    self.net_inflight = false;
                    // Mark everything stale, then revive whatever is present now.
                    for tc in self.net_conns.values_mut() {
                        tc.alive = false;
                    }
                    for conn in snapshot.connections {
                        let key = conn.key();
                        match self.net_conns.get_mut(&key) {
                            Some(tc) => {
                                tc.conn = conn;
                                tc.last_seen = now;
                                tc.alive = true;
                            }
                            None => {
                                self.net_conns.insert(
                                    key,
                                    TrackedConn {
                                        conn,
                                        last_seen: now,
                                        alive: true,
                                    },
                                );
                            }
                        }
                    }
                    // Drop connections that have fully faded out.
                    self.net_conns
                        .retain(|_, tc| tc.alive || (now - tc.last_seen) < NET_FADE_SECS);
                }
                Response::EventSubscriptions { id, report } => {
                    self.pending.remove(&id);
                    self.events_loading = false;
                    self.events_report = Some(report);
                }
                Response::Providers { id, providers } => {
                    self.pending.remove(&id);
                    self.providers_loading = false;
                    self.providers = Some(providers);
                }
                Response::Schema {
                    id, class, schema, ..
                } => {
                    self.pending.remove(&id);
                    if class == self.schema_class {
                        self.schema = Some(schema);
                        self.schema_loading = false;
                    }
                }
                Response::Mof {
                    id,
                    object_path,
                    mof,
                } => {
                    self.pending.remove(&id);
                    if object_path == self.mof_object_path {
                        self.mof_text = Some(mof);
                        self.mof_loading = false;
                    }
                }
                Response::Instances { id, targets, .. } => {
                    self.pending.remove(&id);
                    self.act_instances_loading = false;
                    self.act_instances = Some(targets);
                }
                Response::MethodDone {
                    id,
                    method,
                    outcome,
                    ..
                } => {
                    self.pending.remove(&id);
                    self.act_invoking = false;
                    self.act_outcome = Some((method, outcome));
                }
                Response::SearchIndex { id, index } => {
                    self.pending.remove(&id);
                    self.search_loading = false;
                    self.search_index = Some(index);
                }
                Response::HostConnected { id, host } => {
                    self.pending.remove(&id);
                    self.conn_status = match &host {
                        Some(h) => ConnStatus::Remote(h.clone()),
                        None => ConnStatus::Local,
                    };
                    self.reset_and_reseed();
                }
                Response::Error {
                    id,
                    context,
                    message,
                } => {
                    let kind = self.pending.remove(&id);
                    match kind {
                        Some(PendingKind::Namespaces(ns)) => {
                            self.ns_loading.remove(&ns);
                        }
                        Some(PendingKind::Classes) => {
                            self.classes_loading = false;
                        }
                        Some(PendingKind::Query) => {
                            if id == self.latest_query_id {
                                self.query_loading = false;
                            }
                        }
                        Some(PendingKind::Network) => {
                            self.net_inflight = false;
                        }
                        Some(PendingKind::Events) => {
                            self.events_loading = false;
                        }
                        Some(PendingKind::Providers) => {
                            self.providers_loading = false;
                        }
                        Some(PendingKind::Schema) => {
                            self.schema_loading = false;
                        }
                        Some(PendingKind::Mof) => {
                            self.mof_loading = false;
                        }
                        Some(PendingKind::Instances) => {
                            self.act_instances_loading = false;
                        }
                        Some(PendingKind::Invoke) => {
                            self.act_invoking = false;
                        }
                        Some(PendingKind::Search) => {
                            self.search_loading = false;
                        }
                        Some(PendingKind::Connect) => {
                            self.conn_status = ConnStatus::Failed(message.clone());
                        }
                        None => {}
                    }
                    self.push_error(format!("{context}\n{message}"));
                }
            }
        }
    }

